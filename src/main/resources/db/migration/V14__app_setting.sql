-- What the manager may change without a redeploy (section 10.4's /settings screen).
--
-- One row per overridden property, keyed by the property's own name so a row here and the line it
-- overrides in application.yml are recognisably the same thing. Absence is the default: deleting a
-- row restores the YAML value, which is why there is no "is_default" column to keep in step.
--
-- The value is text and this table does not know what any of it means. Parsing belongs to whichever
-- module owns the key — `dispatch` knows what a weight is, `workflow` knows what an SLA window is.
CREATE TABLE app_setting (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(128) NOT NULL,
    value      VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    updated_by BIGINT       REFERENCES app_user(id),  -- NULL = set before anyone signed in
    CONSTRAINT uq_setting_name UNIQUE (name)
);
