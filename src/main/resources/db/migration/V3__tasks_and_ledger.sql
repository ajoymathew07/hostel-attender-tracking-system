-- Data model section 3.6 — tasks, dockets and the points ledger.
--
-- `uq_ledger_idem` is the second constraint that carries the design. Because the key for an
-- automatic credit is derived deterministically from the work (RESOLVE:{task}:{attender}), a
-- retried request collides on this constraint and is swallowed as a no-op. Double-crediting is not
-- a race we have to win; it is structurally impossible (section 7.3).
--
-- Note what is NOT here: there is no points balance column on `app_user` or anywhere else. A
-- balance is a SUM over this append-only table, so there is no counter to lose an update on
-- (section 7.3). `point_ledger.points` below is the signed amount of one immutable movement, not a
-- running total.

CREATE TABLE task (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type    VARCHAR(16) NOT NULL,     -- COMPLAINT | SPECIAL_DUTY
    complaint_id BIGINT REFERENCES complaint(id),
    title        VARCHAR(255) NOT NULL,
    description  TEXT,
    point_value  INTEGER     NOT NULL,     -- +2 default for complaints; custom for duties
    shared       BOOLEAN     NOT NULL DEFAULT FALSE,
    -- How many attenders may hold an ACTIVE assignment at once: the 'k' of test
    -- X5 and of section 7.6's claim path. Always 1 for an unshared task, so the
    -- claim guard needs no special case for the common path.
    slots        INTEGER     NOT NULL DEFAULT 1,
    status       VARCHAR(24) NOT NULL,
    opens_at     TIMESTAMP,
    closes_at    TIMESTAMP,
    created_by   BIGINT      NOT NULL REFERENCES app_user(id),
    created_at   TIMESTAMP   NOT NULL,
    version      BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_task_type CHECK (task_type IN ('COMPLAINT','SPECIAL_DUTY')),
    CONSTRAINT ck_task_slots CHECK (
        slots >= 1 AND (shared OR slots = 1)),
    CONSTRAINT ck_task_link CHECK (
        (task_type = 'COMPLAINT'    AND complaint_id IS NOT NULL) OR
        (task_type = 'SPECIAL_DUTY' AND complaint_id IS NULL))
);

CREATE TABLE task_assignment (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT      NOT NULL REFERENCES task(id),
    attender_id   BIGINT      NOT NULL REFERENCES app_user(id),
    assign_method VARCHAR(16) NOT NULL,    -- AUTO | MANUAL | CLAIMED
    assigned_by   BIGINT      REFERENCES app_user(id),
    assigned_at   TIMESTAMP   NOT NULL,
    status        VARCHAR(16) NOT NULL,    -- ACTIVE | RELEASED | COMPLETED
    score_snapshot TEXT,                   -- JSON of the dispatch score that chose them
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_task_attender UNIQUE (task_id, attender_id),
    CONSTRAINT ck_asg_method CHECK (assign_method IN ('AUTO','MANUAL','CLAIMED'))
);

-- Append-only. No UPDATE, no DELETE. Reversals are new rows with negated points.
CREATE TABLE point_ledger (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attender_id     BIGINT       NOT NULL REFERENCES app_user(id),
    task_id         BIGINT       REFERENCES task(id),
    reason_code     VARCHAR(32)  NOT NULL,
    points          INTEGER      NOT NULL,  -- signed movement, NOT a balance (section 7.3)
    effective_date  DATE         NOT NULL,  -- Asia/Kolkata business date (NFR-7)
    -- The design writes this as CHAR(7); VARCHAR for the same reason as source_row.response_key.
    period_key      VARCHAR(7)   NOT NULL,  -- 'YYYY-MM', derived from effective_date
    note            VARCHAR(500),
    idempotency_key VARCHAR(128) NOT NULL,
    reverses_id     BIGINT       REFERENCES point_ledger(id),
    created_by      BIGINT       NOT NULL REFERENCES app_user(id),
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_ledger_idem   UNIQUE (idempotency_key),
    CONSTRAINT ck_ledger_reason CHECK (reason_code IN
        ('COMPLAINT_RESOLVED','SPECIAL_DUTY','PENALTY','MANUAL_ADJUSTMENT','REVERSAL'))
);
CREATE INDEX ix_ledger_period  ON point_ledger (period_key, attender_id);
CREATE INDEX ix_ledger_att     ON point_ledger (attender_id, effective_date);
